// Only these four public files are bundled. Database, Python files and secrets are excluded.
import { readFile, writeFile, mkdir } from 'node:fs/promises';
const types = {'dashboard.html':'text/html; charset=utf-8', 'dashboard.js':'text/javascript; charset=utf-8',
  'dashboard.css':'text/css; charset=utf-8', 'favicon.svg':'image/svg+xml'};
const assets = {};
for (const [name, mime] of Object.entries(types)) {
  assets[name === 'dashboard.html' ? '/' : '/' + name] = {body:await readFile(new URL('../'+name,import.meta.url),'utf8'),mime};
}
await mkdir(new URL('src/',import.meta.url),{recursive:true});
await writeFile(new URL('src/assets.mjs',import.meta.url), '// Generated by prepare-assets.mjs; do not edit.\nexport default '+JSON.stringify(assets)+';\n');
